//! Poseidon over BN254's scalar field, as circomlib 2.0.5's `Poseidon(n)` (x^5, 8 full rounds, domain tag zero), for
//! the vault's two widths: t = 3, two inputs (tree nodes; PP's `PoseidonT3`), and t = 4, three inputs (a commitment,
//! PP `PrivacyPool.sol:98` `PoseidonT4.hash([_value, _label, _precommitmentHash])`).
//!
//! The trim build (vault.md 2.6, l.543-551 at ffcba5e): light-poseidon 0.4.1's own `Poseidon`, built by
//! `Poseidon::new` (domain tag zero, as `new_circom`: light-poseidon `src/lib.rs` l.323-325 and l.518-520) from its own
//! circom constants for t = 3 and t = 4, kept below as data. `new_circom` itself is never linked: it pulls in
//! light-poseidon's table of every width, one function body of 1,369,515 B against NEAR's `max_function_body_size` of
//! 196,608 B, so every call of such a build fails with FunctionBodyTooLarge.
//!
//! The constants are copied unchanged from light-poseidon 0.4.1 (Light Protocol, Apache-2.0)
//! `src/parameters/bn254_x5.rs`: the `3 == t` branch (l.853-2095) and the `4 == t` branch (l.2096-3748), each
//! `BigInteger256::new([..])` one canonical field element in four u64 limbs, least significant first; the partial
//! rounds are its `PARTIAL_ROUNDS[t - 2]`. tests/poseidon.rs checks every one against light-poseidon's
//! `get_poseidon_parameters`, and the hashes against circomlib's vectors and Privacy Pools' withdraw circuit (VT-U01).

use crate::field;
use crate::Bytes32;
use ark_bn254::Fr;
use ark_ff::{BigInt, PrimeField};
