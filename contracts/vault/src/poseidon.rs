use near_sdk::env;

/// Poseidon of two field elements (t = 3). Build it once per call and reuse it for every hash.
pub struct PoseidonT3(Poseidon<Fr>);

/// Poseidon of three field elements (t = 4). Build it once per call and reuse it for every hash.
pub struct PoseidonT4(Poseidon<Fr>);

#[allow(clippy::new_without_default)]
impl PoseidonT3 {
    pub fn new() -> Self {
        Self(Poseidon::new(parameters(3, &ARK3, &MDS3, PARTIAL3)))
    }

    /// Poseidon(a, b). Panics with `FieldOverflow` when an input is not below p.
    pub fn hash(&mut self, a: &Bytes32, b: &Bytes32) -> Bytes32 {
        run(&mut self.0, &[to_fr(a), to_fr(b)])
    }
}

#[allow(clippy::new_without_default)]
impl PoseidonT4 {
    pub fn new() -> Self {
        Self(Poseidon::new(parameters(4, &ARK4, &MDS4, PARTIAL4)))
    }

    /// Poseidon(a, b, c). Panics with `FieldOverflow` when an input is not below p.
    pub fn hash(&mut self, a: &Bytes32, b: &Bytes32, c: &Bytes32) -> Bytes32 {
        run(&mut self.0, &[to_fr(a), to_fr(b), to_fr(c)])
    }
}

/// circomlib's parameters for width `t`: 8 full rounds, alpha 5, the given partial rounds, ark and mds.
pub fn parameters(t: usize, ark: &[[u64; 4]], mds: &[[u64; 4]], partial: usize) -> PoseidonParameters<Fr> {
    let f = |x: &[u64; 4]| Fr::from_bigint(BigInt(*x)).unwrap_or_else(|| env::panic_str("Poseidon: a constant is not below p"));
    let ark = ark.iter().map(f).collect();
    let mds = mds.chunks(t).map(|row| row.iter().map(f).collect()).collect();
    PoseidonParameters::new(ark, mds, 8, partial, t, 5)
}

fn run(h: &mut Poseidon<Fr>, inputs: &[Fr]) -> Bytes32 {
    let out = h.hash(inputs).unwrap_or_else(|_| env::panic_str("Poseidon: wrong input count"));
    let le = out.into_bigint().0;
    field::to_be(&[le[3], le[2], le[1], le[0]])
}

/// 32 big-endian bytes to a field element, refusing any value at or above p (never reduced, so no two inputs alias).
fn to_fr(b: &Bytes32) -> Fr {
    let be = field::from_be(b);
    Fr::from_bigint(BigInt([be[3], be[2], be[1], be[0]]))
        .unwrap_or_else(|| env::panic_str("FieldOverflow: a Poseidon input is not below p"))
}

