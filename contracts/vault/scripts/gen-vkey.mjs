// Writes contracts/vault/src/verifier_keys.rs, the vault's two Groth16 verifying keys as compile-time constants, from
// the pinned snarkjs .vkey files in packages/kit/zk/ (Privacy Pools v1.3.0's withdraw and commitment keys). Never
// edit the output by hand.
//   node contracts/vault/scripts/gen-vkey.mjs           write the file
//   node contracts/vault/scripts/gen-vkey.mjs --check   write nothing; exit 1 if the file differs from a fresh run
// tests/vkey.rs runs --check, so cargo test fails when the file and the .vkey files disagree.
//
// Before it reads a number, the script checks each .vkey file's size and sha256 against the kit's frozen pins
// (packages/kit/src/zk/setup-files.ts) and refuses on any mismatch.
//
// Byte order: NEAR's alt_bn128 host functions, read in near-vm-runner 0.37.4 (the crate near-sdk 5.29.1's
// unit-testing feature runs, Cargo.lock), src/logic/alt_bn128.rs lines 113-161, read 2026-11-01:
//   - an Fq is 32 bytes little-endian (decode_u256: u128 lo then u128 hi, each from_le_bytes);
//   - a G1 point is x then y (decode_g1);
//   - a G2 point is x then y (decode_g2), each Fq2 real then imaginary (decode_fq2: Fq2::new(real, imaginary)).
// snarkjs writes an Fq2 as [c0, c1] = [real, imaginary], so a G2 is x.c0, x.c1, y.c0, y.c1. This is the order of the
// research repo's proofs/g1-vault-gas/contract/build.rs, whose constants verified a real withdraw proof in
// near-sandbox 2.13.4 and on testnet. tests/vkey.rs re-proves the order on a real proof through near-vm-runner.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const REPO = join(dirname(fileURLToPath(import.meta.url)), "../../..");
const OUT = join(REPO, "contracts/vault/src/verifier_keys.rs");
const KEYS = ["withdraw", "commitment"];

// BN254's base field q (EIP-196): every coordinate must be below it.
const Q = 21888242871839275222246405745257275088696311157297823662689037894645226208583n;

const fail = (msg) => {
  throw new Error(`gen-vkey: ${msg}`);
};

// A coordinate: a canonical decimal string below q, as 64 hex digits of its 32 little-endian bytes.
function fq(v, what) {
  if (typeof v !== "string" || !/^(0|[1-9]\d*)$/.test(v)) fail(`${what}: not a canonical decimal string`);
  let n = BigInt(v);
  if (n >= Q) fail(`${what}: not below q`);
  let hex = "";
  for (let i = 0; i < 32; i++) {
    hex += Number(n & 0xffn).toString(16).padStart(2, "0");
    n >>= 8n;
  }
  return hex;
}

// snarkjs affine G1: [x, y, "1"] -> [x, y]
function g1(v, what) {
  if (!Array.isArray(v) || v.length !== 3 || v[2] !== "1") fail(`${what}: G1 is not affine [x, y, "1"]`);
  return [
    [fq(v[0], `${what}.x`), "x"],
    [fq(v[1], `${what}.y`), "y"],
  ];
}

// snarkjs affine G2: [[x.c0, x.c1], [y.c0, y.c1], ["1", "0"]] -> [x.c0, x.c1, y.c0, y.c1]
function g2(v, what) {
  if (!Array.isArray(v) || v.length !== 3 || !Array.isArray(v[2]) || v[2].length !== 2 || v[2][0] !== "1" || v[2][1] !== "0")
    fail(`${what}: G2 is not affine [x, y, ["1", "0"]]`);
  const out = [];
  for (const [i, c] of [
    [0, "x"],
    [1, "y"],
  ]) {
    if (!Array.isArray(v[i]) || v[i].length !== 2) fail(`${what}.${c}: Fq2 is not [c0, c1]`);
    out.push([fq(v[i][0], `${what}.${c}.c0`), `${c}.c0 (real)`]);
    out.push([fq(v[i][1], `${what}.${c}.c1`), `${c}.c1 (imaginary)`]);
  }
  return out;
}

// One point as Rust: unhex(concat!("<coord>", // <name> ...))
const point = (indent, parts) =>
  `unhex(concat!(\n${parts.map(([h, name]) => `${indent}    "${h}", // ${name}\n`).join("")}${indent}))`;

async function generate() {
  const { ZK_SETUP_FILES } = await import(pathToFileURL(join(REPO, "packages/kit/src/zk/setup-files.ts")).href);
  let rs = `// SPDX-License-Identifier: Apache-2.0
// @generated by contracts/vault/scripts/gen-vkey.mjs from packages/kit/zk/withdraw.vkey and commitment.vkey. Do not
// edit: run \`node contracts/vault/scripts/gen-vkey.mjs\`. tests/vkey.rs fails when this file differs from a fresh run.
//! The vault's Groth16 verifying keys (Privacy Pools v1.3.0's ceremony keys, packages/kit/zk/NOTICE) in the byte order
//! of NEAR's alt_bn128 host functions: every coordinate 32 bytes little-endian; a G1 point is x then y; a G2 point is
//! x then y, each Fq2 real (c0) then imaginary (c1). Compile-time constants: nothing at run time can change them.

/// A Groth16 verifying key with \`N\` IC points (\`N - 1\` public signals).
pub struct VerifyingKey<const N: usize> {
    pub alpha_g1: [u8; 64],
    pub beta_g2: [u8; 128],
    pub gamma_g2: [u8; 128],
    pub delta_g2: [u8; 128],
    pub ic: [[u8; 64]; N],
}

/// Lowercase hex to bytes, at compile time; a bad string is a build error.
const fn unhex<const L: usize>(s: &str) -> [u8; L] {
    const fn nibble(c: u8) -> u8 {
        match c {
            b'0'..=b'9' => c - b'0',
            b'a'..=b'f' => c - b'a' + 10,
            _ => panic!("verifier_keys: not lowercase hex"),
        }
    }
    let b = s.as_bytes();
    assert!(b.len() == 2 * L, "verifier_keys: wrong hex length");
    let mut out = [0u8; L];
    let mut i = 0;
    while i < L {
        out[i] = (nibble(b[2 * i]) << 4) | nibble(b[2 * i + 1]);
        i += 1;
    }
    out
}
`;
  for (const name of KEYS) {
    const file = `${name}.vkey`;
    const pin = ZK_SETUP_FILES[file];
    if (!pin) fail(`${file}: no pin in packages/kit/src/zk/setup-files.ts`);
    const raw = readFileSync(join(REPO, "packages/kit/zk", file));
    const sha = createHash("sha256").update(raw).digest("hex");
    if (raw.length !== pin.bytes || sha !== pin.sha256)
      fail(`${file}: refused, ${raw.length} bytes sha256 ${sha} is not the pin's ${pin.bytes} bytes sha256 ${pin.sha256}`);
    const vk = JSON.parse(raw.toString("utf8"));
    if (vk.protocol !== "groth16" || vk.curve !== "bn128") fail(`${file}: not a groth16 bn128 key`);
    if (!Number.isSafeInteger(vk.nPublic) || vk.nPublic < 1) fail(`${file}: nPublic`);
    if (!Array.isArray(vk.IC) || vk.IC.length !== vk.nPublic + 1) fail(`${file}: IC is not nPublic + 1 points`);
    const N = vk.IC.length;
    const C = name.toUpperCase();
    rs += `
/// sha256 of packages/kit/zk/${file}, the pin these constants were made from.
pub const ${C}_VKEY_SHA256: &str =
    "${sha}";

/// The ${name} circuit's key: ${vk.nPublic} public signals.
pub const ${C}: VerifyingKey<${N}> = VerifyingKey {
    alpha_g1: ${point("    ", g1(vk.vk_alpha_1, "vk_alpha_1"))},
    beta_g2: ${point("    ", g2(vk.vk_beta_2, "vk_beta_2"))},
    gamma_g2: ${point("    ", g2(vk.vk_gamma_2, "vk_gamma_2"))},
    delta_g2: ${point("    ", g2(vk.vk_delta_2, "vk_delta_2"))},
    ic: [
${vk.IC.map((p, i) => `        ${point("        ", g1(p, `IC[${i}]`))},\n`).join("")}    ],
};
`;
  }
  return rs;
}

const check = process.argv.includes("--check");
const want = await generate();
if (check) {
  let have = "";
  try {
    have = readFileSync(OUT, "utf8");
  } catch {}
  if (have !== want) {
    console.error("gen-vkey: contracts/vault/src/verifier_keys.rs differs from a fresh run; run node contracts/vault/scripts/gen-vkey.mjs");
    process.exit(1);
  }
  console.log("gen-vkey: verifier_keys.rs equals a fresh run");
} else {
  writeFileSync(OUT, want);
  console.log("gen-vkey: wrote contracts/vault/src/verifier_keys.rs");
}
