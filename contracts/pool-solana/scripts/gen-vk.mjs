// Writes src/vk.rs from packages/kit/zk/withdraw.vkey (Privacy Pools v1.3.0's ceremony key, the NEAR vault's
// own): every coordinate 32 bytes big-endian, a G2 point's Fq2 imaginary part (c1) first, the order of Solana's
// alt_bn128 `_be` calls (EIP-197). src/vk.rs's test parses withdraw.vkey again and fails on any difference.
//   node contracts/pool-solana/scripts/gen-vk.mjs
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, "../../../packages/kit/zk/withdraw.vkey");
const raw = readFileSync(src);
const vk = JSON.parse(raw);
if (vk.protocol !== "groth16" || vk.curve !== "bn128" || vk.nPublic !== 8 || vk.IC.length !== 9) throw new Error("not the withdraw key");
const be = (d) => BigInt(d).toString(16).padStart(64, "0");
const g1 = (p) => { if (p[2] !== "1") throw new Error("G1 not affine"); return be(p[0]) + be(p[1]); };
const g2 = (p) => { if (p[2][0] !== "1" || p[2][1] !== "0") throw new Error("G2 not affine"); return be(p[0][1]) + be(p[0][0]) + be(p[1][1]) + be(p[1][0]); };
const sha = createHash("sha256").update(raw).digest("hex");
const out = `// SPDX-License-Identifier: Apache-2.0
// @generated by contracts/pool-solana/scripts/gen-vk.mjs from packages/kit/zk/withdraw.vkey (sha256 ${sha}). Do not edit.
//! The withdraw circuit's Groth16 verifying key (Privacy Pools v1.3.0's ceremony key, packages/kit/zk/NOTICE; the NEAR
//! vault's \`verifier_keys::WITHDRAW\`) in the byte order of Solana's alt_bn128 \`_be\` calls: every coordinate 32 bytes
//! big-endian; G1 = x ‖ y; G2 = x ‖ y, each Fq2 imaginary (c1) ‖ real (c0). Compile-time constants.

pub const ALPHA_G1: [u8; 64] = hex64("${g1(vk.vk_alpha_1)}");
pub const BETA_G2: [u8; 128] = hex128("${g2(vk.vk_beta_2)}");
pub const GAMMA_G2: [u8; 128] = hex128("${g2(vk.vk_gamma_2)}");
pub const DELTA_G2: [u8; 128] = hex128("${g2(vk.vk_delta_2)}");
pub const IC: [[u8; 64]; 9] = [
${vk.IC.map((p) => `    hex64("${g1(p)}"),`).join("\n")}
];

const fn nibble(c: u8) -> u8 {
    match c {
        b'0'..=b'9' => c - b'0',
        b'a'..=b'f' => c - b'a' + 10,
        _ => panic!("vk: not lowercase hex"),
    }
}
const fn hex<const L: usize>(s: &str) -> [u8; L] {
    let b = s.as_bytes();
    assert!(b.len() == 2 * L, "vk: wrong hex length");
    let mut out = [0u8; L];
    let mut i = 0;
    while i < L {
        out[i] = (nibble(b[2 * i]) << 4) | nibble(b[2 * i + 1]);
        i += 1;
    }
    out
}
const fn hex64(s: &str) -> [u8; 64] {
    hex::<64>(s)
}
const fn hex128(s: &str) -> [u8; 128] {
    hex::<128>(s)
}
`;
writeFileSync(join(here, "../src/vk.rs"), out);
console.error("wrote src/vk.rs");
